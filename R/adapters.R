# ---------------------------------------------------------------------------
# CORE source adapters (Phase 2). Each is function(request, retrieved_at) and
# returns a geo_point_series or a terroir_refusal. Every adapter is free
# (free = TRUE at registration). Network calls are wrapped so an adapter
# degrades to a structured refusal rather than crashing collect_point().
#
# Live-verification status:
#   nasapower  -- verified live (no key, installed).
#   silo       -- needs a free SILO API key (an email); refuses if unset.
#   abares     -- gridded extract; live golden pending (large download).
#   modis      -- standard MODISTools::mt_subset; live golden pending.
#   rsi        -- Sentinel-2 via Planetary Computer; live golden pending.
# Golden fixtures are (re)generated by data-raw/regenerate_golden.R.
# ---------------------------------------------------------------------------

# nasapower -- global daily climate + solar, point lon/lat, no key. -----------
.adapter_nasapower <- function(request, retrieved_at) {
  if (is.null(request$start) || is.null(request$end)) {
    return(.refuse("nasapower needs start and end dates", "nasapower", warn = FALSE))
  }
  pars <- request$variables %||% c("T2M", "PRECTOTCORR", "RH2M", "WS2M")
  raw <- tryCatch(
    nasapower::get_power(
      community = "ag",
      lonlat = c(request$lon, request$lat),
      pars = pars,
      dates = c(request$start, request$end),
      temporal_api = "daily"
    ),
    error = function(e) e
  )
  if (inherits(raw, "error")) {
    return(.refuse(paste("nasapower call failed:", conditionMessage(raw)),
                   "nasapower", warn = FALSE))
  }
  raw <- data.table::as.data.table(raw)
  idc <- intersect(c("LON", "LAT", "YEAR", "MM", "DD", "DOY", "YYYYMMDD"), names(raw))
  meas <- setdiff(names(raw), idc)
  long <- data.table::melt(
    raw, id.vars = "YYYYMMDD", measure.vars = meas,
    variable.name = "variable", value.name = "value", variable.factor = FALSE
  )
  long[, date := as.Date(YYYYMMDD)]
  long <- long[, .(date, variable, value = as.numeric(value), unit = NA_character_)]
  new_geo_point_series(
    long, lon = request$lon, lat = request$lat, source = "nasapower",
    source_version = utils::packageVersion("nasapower"),
    license = "NASA POWER (free, public)", retrieved_at = retrieved_at,
    call = sprintf("nasapower::get_power(lonlat=c(%g,%g), pars=c(%s), dates=c('%s','%s'))",
                   request$lon, request$lat, paste(pars, collapse = ","),
                   request$start, request$end)
  )
}

# weatherOz / SILO -- Australia 5 km grid, point drill. Free key = email. -----
.adapter_silo <- function(request, retrieved_at) {
  key <- Sys.getenv("SILO_API_KEY", unset = Sys.getenv("WEATHEROZ_SILO_KEY", unset = ""))
  if (!nzchar(key)) {
    return(.refuse(
      "SILO needs a free API key (your email); set SILO_API_KEY",
      "weatherOz", warn = FALSE
    ))
  }
  vals <- request$variables %||% c("max_temp", "min_temp", "rain")
  out <- tryCatch(
    weatherOz::get_data_drill(
      longitude = request$lon, latitude = request$lat,
      start_date = request$start, end_date = request$end,
      values = vals, api_key = key
    ),
    error = function(e) e
  )
  if (inherits(out, "error")) {
    return(.refuse(paste("weatherOz/SILO call failed:", conditionMessage(out)),
                   "weatherOz", warn = FALSE))
  }
  out <- data.table::as.data.table(out)
  if (!"date" %in% names(out)) {
    return(.refuse("weatherOz/SILO returned no date column (live golden pending)",
                   "weatherOz", warn = FALSE))
  }
  # weatherOz returns wide data with renamed columns (max_temp -> air_tmax,
  # rain -> rainfall, ...). The measurements are every column that is neither an
  # identifier nor a per-value `*_source` provenance column.
  id_cols <- c("longitude", "latitude", "year", "month", "day", "date",
               "elev_m", "extracted")
  src_cols <- grep("_source$", names(out), value = TRUE)
  meas <- setdiff(names(out), c(id_cols, src_cols))
  if (!length(meas)) {
    return(.refuse("weatherOz/SILO returned an unexpected shape (live golden pending)",
                   "weatherOz", warn = FALSE))
  }
  long <- data.table::melt(
    out, id.vars = "date", measure.vars = meas,
    variable.name = "variable", value.name = "value", variable.factor = FALSE
  )
  long <- long[, .(date = as.Date(date), variable, value = as.numeric(value),
                   unit = NA_character_)]
  new_geo_point_series(
    long, lon = request$lon, lat = request$lat, source = "silo",
    source_version = utils::packageVersion("weatherOz"),
    license = "SILO / BOM (CC BY 4.0)", retrieved_at = retrieved_at,
    call = "weatherOz::get_data_drill(...)"
  )
}

# read.abares -- Australian Gridded Farm Data, extracted at the point. --------
.adapter_abares <- function(request, retrieved_at) {
  if (!requireNamespace("terra", quietly = TRUE)) {
    return(.refuse("the abares adapter needs 'terra' for point extraction",
                   "read.abares", warn = FALSE))
  }
  res <- tryCatch({
    r <- read.abares::read_agfd_terra()
    # read_agfd_terra() returns a list of SpatRasters (one per climate-scenario
    # realisation), each with the AGFD variable layers; take the most recent
    # and extract its layers at the point.
    ras <- if (inherits(r, "SpatRaster")) r else r[[length(r)]]
    v <- terra::extract(ras, matrix(c(request$lon, request$lat), ncol = 2))
    v <- as.data.frame(v)
    v <- v[, setdiff(names(v), "ID"), drop = FALSE]
    long <- data.table::data.table(
      date = as.Date(NA), variable = names(v), value = as.numeric(unlist(v[1, ])),
      unit = NA_character_
    )
    long[!is.na(value)]
  }, error = function(e) e)
  if (inherits(res, "error")) {
    return(.refuse(paste("read.abares AGFD extract failed (live golden pending):",
                         conditionMessage(res)), "read.abares", warn = FALSE))
  }
  new_geo_point_series(
    res, lon = request$lon, lat = request$lat, source = "abares",
    source_version = utils::packageVersion("read.abares"),
    license = "ABARES (CC BY 4.0)", retrieved_at = retrieved_at,
    call = "read.abares::read_agfd_terra() |> terra::extract(point)"
  )
}

# MODISTools -- MODIS NDVI/EVI 16-day, point pixel. --------------------------
.adapter_modis <- function(request, retrieved_at) {
  band <- request$variables %||% "250m_16_days_NDVI"
  out <- tryCatch(
    MODISTools::mt_subset(
      product = "MOD13Q1", lat = request$lat, lon = request$lon,
      band = band[1], start = request$start, end = request$end,
      site_name = "terroir", progress = FALSE
    ),
    error = function(e) e
  )
  if (inherits(out, "error")) {
    return(.refuse(paste("MODISTools call failed (live golden pending):",
                         conditionMessage(out)), "MODISTools", warn = FALSE))
  }
  out <- data.table::as.data.table(out)
  dcol <- intersect(c("calendar_date", "date"), names(out))[1]
  if (is.na(dcol) || !"value" %in% names(out)) {
    return(.refuse("MODISTools returned an unexpected shape (live golden pending)",
                   "MODISTools", warn = FALSE))
  }
  # Build from explicit vectors: inside a data.table `j`, the `scale` column
  # would shadow a local `scale`, multiplying by the character column. Compute
  # the scaling in plain R to keep it unambiguous.
  scale_factor <- if ("scale" %in% names(out)) {
    suppressWarnings(as.numeric(out[["scale"]][1]))
  } else {
    NA_real_
  }
  if (length(scale_factor) != 1L || is.na(scale_factor)) scale_factor <- 1
  long <- data.table::data.table(
    date = as.Date(out[[dcol]]),
    variable = band[1],
    value = suppressWarnings(as.numeric(out[["value"]])) * scale_factor,
    unit = "index"
  )
  new_geo_point_series(
    long, lon = request$lon, lat = request$lat, source = "modis",
    source_version = utils::packageVersion("MODISTools"),
    license = "NASA MODIS / ORNL DAAC (free)", retrieved_at = retrieved_at,
    call = sprintf("MODISTools::mt_subset(product='MOD13Q1', band='%s')", band[1])
  )
}

# rsi -- Sentinel-2 (Planetary Computer) NDVI at the point. -------------------
.adapter_rsi <- function(request, retrieved_at) {
  if (!requireNamespace("sf", quietly = TRUE) ||
      !requireNamespace("terra", quietly = TRUE)) {
    return(.refuse("the rsi adapter needs 'sf' and 'terra'", "rsi", warn = FALSE))
  }
  res <- tryCatch({
    pt <- sf::st_sfc(sf::st_point(c(request$lon, request$lat)), crs = 4326)
    aoi <- sf::st_buffer(sf::st_transform(pt, 3857), 200)
    ras <- rsi::get_sentinel2_imagery(
      aoi = aoi, start_date = request$start, end_date = request$end,
      output_filename = tempfile(fileext = ".tif")
    )
    r <- terra::rast(ras)
    # rsi names output bands by the planetary_computer_v1 mapping values, not
    # the asset keys: B08 (NIR) -> "N", B04 (red) -> "R".
    nir <- r[["N"]]; red <- r[["R"]]
    ndvi <- (nir - red) / (nir + red)
    val <- terra::extract(ndvi, terra::vect(sf::st_transform(pt, terra::crs(ndvi))))
    data.table::data.table(
      date = as.Date(request$end %||% request$start),
      variable = "NDVI", value = as.numeric(val[1, 2]), unit = "index"
    )
  }, error = function(e) e)
  if (inherits(res, "error")) {
    return(.refuse(paste("rsi Sentinel-2 NDVI failed (live golden pending):",
                         conditionMessage(res)), "rsi", warn = FALSE))
  }
  new_geo_point_series(
    res, lon = request$lon, lat = request$lat, source = "stac",
    source_version = utils::packageVersion("rsi"),
    license = "Copernicus Sentinel-2 via Planetary Computer (free)",
    retrieved_at = retrieved_at,
    call = "rsi::get_sentinel2_imagery(point buffer) -> NDVI"
  )
}
