# ocular -- Sentinel-2 / Landsat spectral-index series over a square window
# around the point, retrieved from the Microsoft Planetary Computer STAC by
# ocular (AAGI-AUS). ocular is an *upstream*, never an orchestra member: it is
# declared in Suggests, is called only through `requireNamespace()`, and every
# condition it raises is converted into a `terroir_refusal` here.
#
# Request mapping (documented in the vignette's source table):
#   `variables[1]` -- the spectral index name (default "NDVI");
#   `variables[2]` -- the sensor, one of "auto" (default), "sentinel-2",
#                     "landsat-8", "landsat-5".
#
# IOP NOTES.
#   1. The collection ids terroir asserts (`sentinel-2-l2a`, `landsat-c2-l2`)
#      are registered in `terroir_external_facts()` and diffed against the
#      Planetary Computer STAC catalogue -- the authority that owns them -- by
#      the catalogue-diff oracle. At call time the adapter additionally checks
#      the registered id against the collection ocular actually configures, and
#      refuses on a mismatch rather than mislabelling the provenance.
#   2. Cloud masking is ON by default and is applied *here*, not upstream. See
#      `.ocular_scene_cloud_mask()` for why, and for the class sets used.
#   3. The scene ids recorded in provenance are read verbatim out of the asset
#      URLs the retrieval returned; nothing is constructed. The signed URLs
#      themselves are never recorded (they carry a time-limited signature).
# ---------------------------------------------------------------------------

# The ocular commit terroir was developed and grounded against. `Remotes:` in
# DESCRIPTION pins the same commit; the adapter reports the commit actually
# installed (read from ocular's own DESCRIPTION), never this constant, so a
# drifted install is visible in the provenance rather than papered over.
.OCULAR_PINNED_COMMIT <- "3317d806806185d1cf509515212d4f2c9cb16e80"

# Sentinel-2 Scene Classification Layer classes masked out by default:
# 0 no-data, 1 saturated/defective, 3 cloud shadow, 8 cloud medium probability,
# 9 cloud high probability, 10 thin cirrus, 11 snow/ice.
.OCULAR_SCL_DEFAULT <- c(0L, 1L, 3L, 8L, 9L, 10L, 11L)

# Landsat Collection-2 QA_PIXEL bit positions masked out by default:
# 0 fill, 1 dilated cloud, 2 cirrus, 3 cloud, 4 cloud shadow, 5 snow. The SCL
# class set above is Sentinel-2 semantics and is meaningless as a bit set, so
# the Landsat path gets its own defaults rather than the wrong ones.
.OCULAR_QA_BIT_DEFAULT <- c(0L, 1L, 2L, 3L, 4L, 5L)

# Side length in metres of the square window centred on the requested point.
# The series value for a date is the window mean, so this is a real semantic:
# 500 m is a 25 ha field-scale window (the value the intake pilot ran on).
.OCULAR_BOX_METRES <- 500L

# Scene-level cloud ceiling (per cent) passed to the STAC search. Scene-level
