# One-shot state for the vendored upstream patch (see .ocular_apply_patch).
.terroir_ocular_state <- new.env(parent = emptyenv())

# --- vendored upstream patch ------------------------------------------------
# VENDORED UPSTREAM PATCH, pending the fix upstream. ocular's internal
# `.mergeRasterTiles()` hands a *named* list of rasters to `do.call()`, so the
# merge call receives named arguments, no argument matches the generic's first
# formal, and every multi-tile date fails with `argument "x" is missing`. The
# replacement below is behaviourally identical except that the list is unnamed
# before it is spliced into the call. It is installed into ocular's namespace
# on first use of this adapter (never at package load: terroir must not mutate
# an upstream it may never call), once per session, and only if the upstream
# function still has the defect's shape. Remove when ocular ships the fix.
.ocular_merge_raster_tiles <- function(rasters, method = "bilinear") {
  rasters <- Filter(Negate(is.null), unname(rasters))
  if (!length(rasters)) return(NULL)
  if (length(rasters) == 1L) return(rasters[[1L]])
  ref_crs <- terra::crs(rasters[[1L]])
  aligned <- lapply(rasters, function(r) {
    if (identical(terra::crs(r), ref_crs)) {
      r
    } else {
      terra::project(r, ref_crs, method = method)
    }
  })
  merged <- do.call(
    terra::merge,
    c(unname(aligned), list(algo = 3, method = method, na.rm = TRUE))
  )
  merged * 1
}

# Install the vendored patch once per session. Returns TRUE when the patch is
# in place (already-patched counts), FALSE when it could not be installed --
# the caller refuses rather than running an upstream known to fail on any
# multi-tile date.
.ocular_apply_patch <- function() {
  if (isTRUE(.terroir_ocular_state$patched)) return(TRUE)
  ok <- tryCatch({
    utils::assignInNamespace(".mergeRasterTiles",
                             .ocular_merge_raster_tiles, ns = "ocular")
    TRUE
  }, error = function(e) FALSE)
  .terroir_ocular_state$patched <- ok
  ok
}

# --- upstream condition boundary --------------------------------------------
# Run one ocular call so that nothing untyped escapes the adapter. ocular
# signals plain `simpleError` / `simpleWarning` conditions, so there is no
# upstream class to dispatch on and this wrapper is the type boundary: an error
# becomes a refusal, and so does a warning -- ocular warns when it silently
# degrades a retrieval (a failed tile merge falling back to one tile), which is
# exactly the outcome terroir must not pass on as if it were clean data.
# Progress messages are suppressed.
.ocular_guard <- function(expr, what) {
  warned <- character()
  val <- withCallingHandlers(
    tryCatch(suppressMessages(expr), error = function(e) e),
    warning = function(w) {
      warned[[length(warned) + 1L]] <<- conditionMessage(w)
      invokeRestart("muffleWarning")
    }
  )
  if (inherits(val, "error")) {
    return(.refuse(paste0("ocular ", what, " failed: ", conditionMessage(val)),
                   "ocular", warn = FALSE))
  }
  if (length(warned)) {
    return(.refuse(
      paste0("ocular ", what, " warned, so the retrieval is degraded: ",
             paste(warned, collapse = "; ")),
      "ocular", warn = FALSE
    ))
  }
  val
}

# --- provenance helpers -----------------------------------------------------
# The scene identifier read out of a scene's asset URLs. ocular's scene records
# do not retain the STAC item id, so this takes the product id that is present
# verbatim in the URL path and returns NA when neither form is found -- never a
# reconstructed id. The URL itself is discarded (it carries an access
# signature).
.ocular_scene_id <- function(assets) {
  hrefs <- sub("\\?.*$", "", as.character(unlist(assets, use.names = FALSE)))
  for (pat in .OCULAR_SCENE_ID_PATTERNS) {
    hit <- regmatches(hrefs, regexpr(pat, hrefs))
    if (length(hit)) return(hit[[1L]])
  }
  NA_character_
}

# The ocular commit actually installed, read from its own DESCRIPTION. NA when
# the install carries no commit metadata (a local build, say) -- reported as NA
# rather than assumed to be the pinned commit.
.ocular_installed_commit <- function() {
  desc <- utils::packageDescription("ocular")
  sha <- desc$RemoteSha %||% desc$GithubSHA1
  if (is.null(sha) || !nzchar(sha)) NA_character_ else as.character(sha)
}

# --- cloud masking ----------------------------------------------------------
# Pixel cloud masking, applied by terroir to each scene's index raster.
#
# WHY HERE AND NOT UPSTREAM. ocular takes an `scl_classes` argument, but at the
# pinned commit that path is dead: the band list it builds is a *named* list, so
# `do.call(c, bands)` never dispatches to terra's method and returns a plain
# list; the mask branch then calls `terra::resample()` on that list, which
# errors, and the per-scene handler turns the error into a dropped scene. The
# visible symptom is that supplying `scl_classes` returns "No usable scenes"
# for every request. Rather than vendor that whole function (it is large, and
# copying it would carry its licence into this package), the adapter passes
# `scl_classes = NULL` upstream and masks the returned index rasters here.
# Masking the index is equivalent to masking the bands it was computed from,
# because every index ocular supports is computed pixel-wise.
#
# A pixel with no mask coverage is left in place: masking on absent evidence
# would silently discard real observations. A date whose window is fully masked
# aggregates to NA upstream and is dropped from the series by the adapter. A
# whole scene with no pixel-quality asset is a different thing and aborts: it
# cannot be masked, and returning it inside a series advertised as cloud-masked
# would be the silent degradation this adapter exists to prevent.
.ocular_scene_cloud_mask <- function(scene, mask_asset, mask_kind, classes) {
  href <- scene$item_assets[[mask_asset]]
  if (is.null(href) || !length(href)) {
    stop("scene of ", as.character(scene$date), " carries no '", mask_asset,
         "' asset, so it cannot be cloud-masked", call. = FALSE)
  }
  tiles <- lapply(as.character(unlist(href, use.names = FALSE)), function(h) {
    r <- terra::rast(paste0("/vsicurl/", h))
    terra::scoff(r) <- NULL
    if (terra::same.crs(r, scene$index)) {
      terra::resample(r, scene$index, method = "near")
    } else {
      terra::project(r, scene$index, method = "near")
    }
  })
  mb <- if (length(tiles) == 1L) {
    tiles[[1L]]
  } else {
    Reduce(function(a, b) terra::cover(a, b), tiles)
  }
  if (identical(mask_kind, "scl")) {
    Reduce(`|`, lapply(classes, function(k) mb == k))
  } else {
    bits <- sum(vapply(classes, function(b) bitwShiftL(1L, as.integer(b)),
                       integer(1)))
    terra::app(mb, function(v) bitwAnd(as.integer(v), bits) != 0L)
  }
}

# --- the adapter ------------------------------------------------------------
.adapter_ocular <- function(request, retrieved_at) {
  # Request validation first, so a malformed request is answered the same way
  # whether or not the optional upstream is installed on this machine.
  if (is.null(request$start) || is.null(request$end)) {
    return(.refuse("ocular needs start and end dates", "ocular", warn = FALSE))
  }
  vars <- request$variables %||% "NDVI"
  index_name <- as.character(vars)[1L]
  sensor <- if (length(vars) >= 2L) as.character(vars)[2L] else "auto"
  if (!sensor %in% .OCULAR_SENSORS) {
    return(.refuse(
      paste0("unknown ocular sensor '", sensor, "' in variables[2]; one of ",
             paste(.OCULAR_SENSORS, collapse = ", ")),
      "ocular", warn = FALSE
    ))
  }
  if (!requireNamespace("ocular", quietly = TRUE)) {
    return(.refuse(
      paste0("the ocular adapter needs the 'ocular' package, which is not ",
             "installed; install the pinned commit with ",
             "remotes::install_github(\"AAGI-AUS/ocular@",
             .OCULAR_PINNED_COMMIT, "\")"),
      "ocular", warn = FALSE
    ))
  }
  if (!requireNamespace("terra", quietly = TRUE) ||
      !requireNamespace("sf", quietly = TRUE)) {
    return(.refuse("the ocular adapter needs 'terra' and 'sf'",
                   "ocular", warn = FALSE))
  }
  if (!.ocular_apply_patch()) {
    return(.refuse(
      paste0("could not install the vendored fix for ocular's tile merge; ",
             "an unpatched ocular fails on any multi-tile date, so the ",
             "retrieval is refused rather than run"),
      "ocular", warn = FALSE
    ))
  }

  rs <- .ocular_guard(
    ocular::get_rs(
      longitude = request$lon, latitude = request$lat,
      start_date = request$start, end_date = request$end,
      index_name = index_name, source = sensor,
      x_metres = .OCULAR_BOX_METRES, y_metres = .OCULAR_BOX_METRES,
      max_cloud_cover = .OCULAR_MAX_CLOUD,
      scl_classes = NULL
    ),
    "retrieval"
  )
  if (is_refusal(rs)) return(rs)
  if (is.null(rs$scenes) || !length(rs$scenes)) {
    return(.refuse("ocular returned no usable scenes for this point and range",
                   "ocular", warn = FALSE))
  }

  # Resolve the sensor ocular actually used, and check terroir's asserted
  # collection id against the one ocular configured for it (IOP note 1).
  resolved <- as.character(rs$geom$source %||% sensor)
  asserted <- unname(.OCULAR_COLLECTIONS[resolved])
  cfg <- tryCatch(utils::getFromNamespace(".stacCfg", "ocular")(resolved),
                  error = function(e) NULL)
  if (is.null(cfg) || is.na(asserted) ||
      !identical(as.character(cfg$collection), asserted)) {
    return(.refuse(
      paste0("cannot confirm the STAC collection for sensor '", resolved,
             "': terroir asserts '", asserted, "', ocular configured '",
             as.character(cfg$collection %||% NA_character_), "'"),
      "ocular", warn = FALSE
    ))
  }

  mask_classes <- if (identical(cfg$mask_kind, "scl")) {
    .OCULAR_SCL_DEFAULT
  } else {
    .OCULAR_QA_BIT_DEFAULT
  }
  if (is.null(cfg$mask_asset)) {
    return(.refuse(
      paste0("sensor '", resolved, "' carries no pixel-quality asset, so the ",
             "series cannot be cloud-masked; refusing rather than returning ",
             "an unmasked series"),
      "ocular", warn = FALSE
    ))
  }
  masked <- .ocular_guard(
    lapply(rs$scenes, function(sc) {
      cloud <- .ocular_scene_cloud_mask(sc, cfg$mask_asset, cfg$mask_kind,
                                        mask_classes)
      sc$index <- terra::mask(sc$index, cloud, maskvalue = TRUE)
      sc
    }),
    "cloud masking"
  )
  if (is_refusal(masked)) return(masked)
  rs$scenes <- masked

  ts <- .ocular_guard(ocular::as_time_series(rs), "series aggregation")
  if (is_refusal(ts)) return(ts)
  ts <- data.table::as.data.table(ts)
  if (!all(c("date", "value") %in% names(ts))) {
    return(.refuse("ocular returned an unexpected time-series shape",
                   "ocular", warn = FALSE))
  }
  long <- ts[, .(date = as.Date(date), variable = index_name,
                 value = as.numeric(value), unit = "index")]
  long <- long[is.finite(value)]
  if (!nrow(long)) {
    return(.refuse(
      paste0("every scene in range was fully cloud-masked, so ocular returned ",
             "no usable ", index_name, " value at this point"),
      "ocular", warn = FALSE
    ))
  }

  series <- new_geo_point_series(
    long, lon = request$lon, lat = request$lat, source = "ocular",
    source_version = utils::packageVersion("ocular"),
    license = paste("Copernicus Sentinel-2 / USGS Landsat via Microsoft",
                    "Planetary Computer (free); retrieved with ocular",
                    "(AAGI-AUS, GPL-3)"),
    retrieved_at = retrieved_at,
    call = sprintf(
      paste0("ocular::get_rs(longitude=%g, latitude=%g, index_name='%s', ",
             "source='%s', x_metres=%d, max_cloud_cover=%g) |> ",
             "as_time_series()"),
      request$lon, request$lat, index_name, resolved,
      .OCULAR_BOX_METRES, .OCULAR_MAX_CLOUD
    )
  )
  scene_dates <- as.character(as.Date(
    vapply(rs$scenes, function(sc) as.character(sc$date), character(1))
  ))
  prov <- attr(series, "provenance")
  prov$stac_endpoint <- .OCULAR_STAC_ENDPOINT
  prov$stac_collection <- asserted
  prov$sensor <- resolved
  prov$index_name <- index_name
  prov$box_metres <- .OCULAR_BOX_METRES
  prov$max_cloud_cover <- .OCULAR_MAX_CLOUD
  prov$mask_asset <- as.character(cfg$mask_asset)
  prov$mask_kind <- as.character(cfg$mask_kind)
  prov$mask_classes <- mask_classes
  prov$scene_dates <- scene_dates
  prov$scene_ids <- vapply(rs$scenes,
                           function(sc) .ocular_scene_id(sc$item_assets),
                           character(1))
  prov$ocular_commit <- .ocular_installed_commit()
  prov$ocular_commit_pinned <- .OCULAR_PINNED_COMMIT
  prov$vendored_patches <- "ocular:::.mergeRasterTiles (unnamed merge call)"
  data.table::setattr(series, "provenance", prov)
  series
}

# ---- ISRIC SoilGrids: the global soil profile -------------------------------
#
# The gap a running study had to route around. A grain decision needs soil --
# texture, pH, plant-available water, starting nitrogen -- as much as it needs
# weather, and terroir served none; `studies/A0/01_generate_belt.R` reached past
# terroir into apsimx for exactly this and left the uplift note behind.
#
# Non-intersecting by design. `nert` already serves TERN soil, but only over
# Australia and only with a key. This source is global and keyless, so the two
# complement rather than duplicate: inside Australia a caller may prefer TERN's
# measured products, everywhere else this is the only soil terroir has.
#
# Soil is time-invariant at the scale terroir serves, so `date` is NA. That is
# deliberate rather than missing: stamping the retrieval date onto a property
# that does not vary would invite a consumer to read it as a series and to
# difference two retrievals as though something had changed.

#: The soil properties this adapter serves, mapped to the upstream's columns.
.SOIL_VARS <- c(
  clay = "ParticleSizeClay", silt = "ParticleSizeSilt", sand = "ParticleSizeSand",
  carbon = "Carbon", ph = "PH", bd = "BD", cec = "CEC", nitrogen = "Nitrogen",
  ll15 = "LL15", dul = "DUL", sat = "SAT"
)

#: Units, carried into the contract's `unit` column so a consumer never guesses.
.SOIL_UNITS <- c(
  clay = "%", silt = "%", sand = "%", carbon = "%", ph = "pH",
  bd = "g/cm3", cec = "cmol/kg", nitrogen = "%",
  ll15 = "mm/mm", dul = "mm/mm", sat = "mm/mm"
)

.adapter_isric <- function(request, retrieved_at) {
  want <- request$variables %||% names(.SOIL_VARS)
  unknown <- setdiff(want, names(.SOIL_VARS))
  if (length(unknown) > 0L) {
    return(.refuse(
      sprintf("isric serves no variable(s) %s; it serves %s",
              paste(unknown, collapse = ", "),
              paste(names(.SOIL_VARS), collapse = ", ")),
      "isric", warn = FALSE
    ))
  }
  # The distributional handle, and its limit. ISRIC publishes Q0.05 / Q0.5 /
  # Q0.95 per property, which is what would let soil enter an analysis as a
  # prior rather than a point. The upstream wrapper exposes only the mean and
  # the median, so that is all this adapter can offer; the quantile
  # layers are the concrete blocker to a Bayesian use and are recorded as such
  # rather than approximated from the mean-median gap.
  stat_local <- request$statistic %||% "mean"
  if (!stat_local %in% c("mean", "Q0.5")) {
    return(.refuse(
      sprintf(paste("isric serves statistic 'mean' or 'Q0.5', not '%s';",
                    "the upstream exposes no other quantile"), stat_local),
      "isric", warn = FALSE
    ))
  }
  raw <- tryCatch(
    apsimx::get_isric_soil_profile(lonlat = c(request$lon, request$lat),
                                   statistic = stat_local,
                                   fix = TRUE, verbose = FALSE),
    error = function(e) e
  )
  if (inherits(raw, "error")) {
    return(.refuse(paste("isric call failed:", conditionMessage(raw)),
                   "isric", warn = FALSE))
  }
  sp <- raw$soil
  if (is.null(sp) || !is.data.frame(sp) || nrow(sp) == 0L) {
    return(.refuse("isric returned no soil layers for this point",
                   "isric", warn = FALSE))
  }
  if (!"Depth" %in% names(sp)) {
    return(.refuse("isric profile carries no Depth column", "isric", warn = FALSE))
  }
  have <- want[.SOIL_VARS[want] %in% names(sp)]
  if (length(have) == 0L) {
    return(.refuse(
      sprintf("isric profile carries none of the requested columns (%s)",
              paste(want, collapse = ", ")),
      "isric", warn = FALSE
    ))
  }
  depth_tag <- paste0(gsub("-", "_", as.character(sp$Depth), fixed = TRUE), "cm")
  rows_list <- vector("list", length(have))
  for (i1 in seq_along(have)) {
    v_local <- have[i1]
    rows_list[[i1]] <- data.table::data.table(
      date = as.Date(NA),
      variable = paste0(v_local, "_", depth_tag),
      value = suppressWarnings(as.numeric(sp[[.SOIL_VARS[v_local]]])),
      unit = unname(.SOIL_UNITS[v_local])
    )
  } # ends i1, over the requested soil properties
  long <- data.table::rbindlist(rows_list)
  long <- long[is.finite(long$value), ]
  if (nrow(long) == 0L) {
    return(.refuse("isric returned no finite soil values for this point",
                   "isric", warn = FALSE))
  }
  new_geo_point_series(
    long, lon = request$lon, lat = request$lat, source = "isric",
    source_version = utils::packageVersion("apsimx"),
    license = "ISRIC SoilGrids (CC-BY 4.0), retrieved via apsimx",
    retrieved_at = retrieved_at,
    call = sprintf(paste0("apsimx::get_isric_soil_profile(lonlat=c(%g,%g), ",
                          "statistic='%s', fix=TRUE)"),
                   request$lon, request$lat, stat_local)
  )
}
